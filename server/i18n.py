def translate(locale: str, key: str) -> str:
    loc = locale if locale in LOCALES else "en"
    return STRINGS.get(loc, {}).get(key) or STRINGS["en"].get(key, key)


def resolve_locale(req: Request) -> str:
    c = req.cookies.get(COOKIE_NAME)
    if c in LOCALES:
        return c
    al = (req.headers.get("Accept-Language") or "").lower()
    if al.startswith("de"):
        return "de"
    return "en"


def central_js_strings(locale: str) -> dict[str, str]:
    """All UI strings for client-side scripts (dots → underscores)."""
    loc = locale if locale in LOCALES else "en"
    skip_nav = {"nav.dashboard", "nav.events", "nav.flasher", "nav.settings", "nav.lang_en", "nav.lang_de"}
    out: dict[str, str] = {}
    for k in STRINGS["en"]:
        if k in skip_nav:
            continue
        out[k.replace(".", "_")] = translate(loc, k)
    return out
